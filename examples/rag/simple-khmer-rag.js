#!/usr/bin/env node

/**
 * Minimal Zero-Dependency RAG Retrieval Demonstration
 * 
 * Shows how an AI pipeline searches the reference dataset
 * and augments an LLM prompt with verified Khmer terminology.
 */

const fs = require('fs');
const path = require('path');

const DIST_PATH = path.resolve(__dirname, '../../dist/khmer-ai-reference.json');

// Ensure dist bundle exists
if (!fs.existsSync(DIST_PATH)) {
  console.log('Building dist bundle first...');
  require('../../tools/compiler/build-dist.js');
}

const referenceBundle = JSON.parse(fs.readFileSync(DIST_PATH, 'utf8'));
const terms = referenceBundle.terms;

/**
 * Searches reference terms that appear in the input query text.
 */
function findRelevantTerms(queryText, domainFilter = null) {
  const normalizedQuery = queryText.toLowerCase();
  const matches = [];

  for (const item of terms) {
    if (domainFilter && item.domain !== domainFilter) continue;

    const termLower = item.term.toLowerCase();
    // Match exact phrase / word boundary
    const regex = new RegExp(`\\b${termLower}\\b`, 'i');
    if (regex.test(normalizedQuery)) {
      matches.push(item);
    }
  }

  // Sort matches by term length descending so multi-word terms take precedence
  return matches.sort((a, b) => b.term.length - a.term.length);
}

/**
 * Constructs an augmented prompt for the LLM.
 */
function buildAugmentedPrompt(sentenceToTranslate, domain = null) {
  const matchedTerms = findRelevantTerms(sentenceToTranslate, domain);

  let prompt = `You are an expert translator specializing in natural, accurate Khmer.\n\n`;
  prompt += `Translate the following sentence into Khmer:\n`;
  prompt += `"${sentenceToTranslate}"\n\n`;

  if (matchedTerms.length > 0) {
    prompt += `CRITICAL: Before translating, adhere strictly to these verified Khmer terms:\n`;
    matchedTerms.forEach(t => {
      prompt += `- "${t.term}" -> "${t.preferredKhmer}" [Domain: ${t.domain}, Context: ${t.context || 'general'}]\n`;
    });
    prompt += `\n`;
  } else {
    prompt += `No specific verified terminology match found. Use natural Khmer phrasing.\n\n`;
  }

  prompt += `Khmer Translation:`;
  return prompt;
}

// Demo Execution
const demoSentence = "The system administrator enabled two-factor authentication and restored the database from backup.";
console.log("=== Original Input Sentence ===");
console.log(demoSentence);
console.log("\n=== Augmented LLM Prompt Generated by Reference Layer ===");
console.log(buildAugmentedPrompt(demoSentence));
