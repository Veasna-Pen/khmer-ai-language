#!/usr/bin/env node
// Minimal RAG demo: finds reference terms in a sentence and builds a terminology-grounded translation prompt.

const { loadBundle } = require('../../tools/lib/dataset');

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function findRelevantTerms(terms, text, domain = null) {
  return terms
    .filter((t) => !domain || t.domain === domain)
    .filter((t) => new RegExp(`\\b${escapeRegExp(t.term)}\\b`, 'i').test(text))
    .sort((a, b) => b.term.length - a.term.length); // longer phrases first, e.g. "two-factor authentication" before "authentication"
}

function buildAugmentedPrompt(terms, sentence, domain = null) {
  const matches = findRelevantTerms(terms, sentence, domain);
  const glossary = matches.length
    ? 'CRITICAL: Before translating, adhere strictly to these verified Khmer terms:\n' +
      matches.map((t) => `- "${t.term}" -> "${t.preferredKhmer}" [Domain: ${t.domain}, Context: ${t.context || 'general'}]\n`).join('') +
      '\n'
    : 'No specific verified terminology match found. Use natural Khmer phrasing.\n\n';

  return [
    'You are an expert translator specializing in natural, accurate Khmer.\n\n',
    'Translate the following sentence into Khmer:\n',
    `"${sentence}"\n\n`,
    glossary,
    'Khmer Translation:',
  ].join('');
}

if (require.main === module) {
  const { terms } = loadBundle();
  const sentence = process.argv[2] || 'The system administrator enabled two-factor authentication and restored the database from backup.';
  console.log('=== Original Input Sentence ===');
  console.log(sentence);
  console.log('\n=== Augmented LLM Prompt Generated by Reference Layer ===');
  console.log(buildAugmentedPrompt(terms, sentence));
}

module.exports = { findRelevantTerms, buildAugmentedPrompt };
